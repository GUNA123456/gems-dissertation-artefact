#!/usr/bin/env python3
"""Generate the Night B magnitude-ladder manifests from the verified standard
ramps (Step4_Collection_Design.md §2, Night B).

Each variant is the standard manifest with metadata.name suffixed and stage
values remapped in a SINGLE regex pass (dict lookup on the original value),
so overlapping ladders (e.g. redis 400→1600 while 1600→3200) cannot cascade.

Design notes, pre-registered here rather than discovered later:
  * cart light peaks at 112MB stress (~147Mi working set, limit 256Mi): no
    OOM expected — a deliberate near-threshold NEGATIVE class.
  * cart heavy is 1.5x (the design doc's ±50%), crossing the 256Mi limit by
    stage 3: earlier OOM, steeper precursor.
  * payment heavy (up to 2200ms) may cross probe/request timeout windows the
    standard ramp deliberately avoids — errors appearing there is signal.
  * catalog has a LIGHT variant only: heavy CPU stress (>=3 stress-ng workers
    at 100%) on the 2-vCPU VM contends with the control plane, kubelet and
    Prometheus, confounding "service fault" with "infrastructure fault" and
    risking the scheduler's own probes. Excluded on those grounds.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(
    HERE, "..", "..", "..", "GEMS_Model_Sandbox", "chaos_manifests", "v2_ramped"))

# base file -> {suffix: {field: {original: replacement}}}
VARIANTS = {
    "redis-delay-ramp.yaml": {
        "light": {"latency": {"150ms": "75ms", "400ms": "200ms",
                              "900ms": "450ms", "1600ms": "800ms"},
                  "jitter": {"30ms": "15ms", "60ms": "30ms",
                             "120ms": "60ms", "250ms": "125ms"}},
        "heavy": {"latency": {"150ms": "800ms", "400ms": "1600ms",
                              "900ms": "2400ms", "1600ms": "3200ms"},
                  "jitter": {"30ms": "125ms", "60ms": "250ms",
                             "120ms": "375ms", "250ms": "500ms"}},
    },
    "payment-delay-ramp.yaml": {
        "light": {"latency": {"100ms": "50ms", "300ms": "150ms",
                              "800ms": "400ms", "1100ms": "550ms"},
                  "jitter": {"20ms": "10ms", "50ms": "25ms",
                             "100ms": "50ms", "80ms": "40ms"}},
        "heavy": {"latency": {"100ms": "200ms", "300ms": "600ms",
                              "800ms": "1600ms", "1100ms": "2200ms"},
                  "jitter": {"20ms": "40ms", "50ms": "100ms",
                             "100ms": "200ms", "80ms": "160ms"}},
    },
    "cart-mem-ramp.yaml": {
        "light": {"size": {"96MB": "48MB", "144MB": "72MB",
                           "192MB": "96MB", "224MB": "112MB"}},
        "heavy": {"size": {"96MB": "144MB", "144MB": "216MB",
                           "192MB": "288MB", "224MB": "336MB"}},
    },
    "catalog-cpu-ramp.yaml": {
        "light": {"load": {"30": "15", "70": "35", "90": "45", "100": "50"},
                  "workers": {"2": "1", "3": "2"}},
    },
}


def remap(text, field, table):
    # match e.g.  latency: '400ms'   |   size: '96MB'   |   load: 70
    pat = re.compile(r"(%s:\s*'?)(%s)('?)" %
                     (field, "|".join(re.escape(k) for k in table)))
    return pat.sub(lambda m: m.group(1) + table[m.group(2)] + m.group(3), text)


for base, variants in VARIANTS.items():
    src = open(os.path.join(SRC, base)).read()
    stem = base[:-len(".yaml")]
    for suffix, fields in variants.items():
        out = src
        for field, table in fields.items():
            out = remap(out, field, table)
        out = out.replace("name: %s" % stem, "name: %s-%s" % (stem, suffix), 1)
        out = ("# NIGHT-B %s VARIANT of %s — generated by make_nightb_variants.py\n"
               % (suffix.upper(), base)) + out
        path = os.path.join(SRC, "%s-%s.yaml" % (stem, suffix))
        open(path, "w").write(out)
        print("wrote", path)
