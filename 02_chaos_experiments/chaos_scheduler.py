BAG = list(RAMPS.keys()) + ["pod-kill"]


def parse_bag(spec):
    """--bag 'a,b,b,c' -> shuffled-bag items; repeats are weights (Step 4
    Night A: cart-mem x2, pod-kill excluded). Default preserves v2run."""
    items = [s.strip() for s in spec.split(",") if s.strip()]
    bad = [s for s in items if s not in RAMPS and s != "pod-kill"]
    if bad:
        raise SystemExit("unknown bag scenario(s): %s (valid: %s)"
                         % (", ".join(bad), ", ".join(BAG)))
    return items

CHAOS_KINDS = "workflow,networkchaos,stresschaos,podchaos"
NS = "default"

# ---------------------------------------------------------------- kubectl --
def kubectl(args, timeout=30, retries=1, quiet=False):
    """Run kubectl; never raises. Returns (rc, stdout). One retry by default."""
    cmd = ["kubectl"] + args
    for attempt in range(retries + 1):
        try:
            p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
            if p.returncode == 0:
                return 0, p.stdout
            err = p.stderr.strip()
        except subprocess.TimeoutExpired:
            err = f"timeout after {timeout}s"
        except Exception as e:  # noqa: BLE001 - the night must continue
            err = f"{type(e).__name__}: {e}"
        if attempt < retries:
            time.sleep(3)
    if not quiet:
        print(f"  [kubectl-fail] {' '.join(args[:6])}: {err}", flush=True)
    return 1, err


def kubectl_json(args, timeout=30):
    rc, out = kubectl(args + ["-o", "json"], timeout=timeout)
    if rc != 0:
        return None
    try:
        return json.loads(out)
    except json.JSONDecodeError:
        return None


# ---------------------------------------------------------------- logging --
class GroundTruthLog:
    def __init__(self, path):
        self.f = open(path, "a", buffering=1)
        self.lock = threading.Lock()

    def write(self, rec):
        rec = dict(rec)
        rec.setdefault("ts", round(time.time(), 3))
        rec.setdefault("iso", datetime.now(timezone.utc).isoformat(timespec="seconds"))
        with self.lock:
            self.f.write(json.dumps(rec) + "\n")
            self.f.flush()
        kind = rec.get("type", "?")
        extra = rec.get("scenario") or rec.get("status") or rec.get("reason") or ""
        print(f"[{rec['iso']}] {kind} {extra}", flush=True)


# ----------------------------------------------------------- cluster state --
def pods_ready():
    """(ready_count, total, traffic_gen_running)."""
    data = kubectl_json(["get", "pods", "-n", NS])
    if data is None:
        return -1, -1, False
    ready = total = 0
    tgen = False
    for p in data.get("items", []):
        total += 1
        statuses = p.get("status", {}).get("containerStatuses", [])
        ok = bool(statuses) and all(c.get("ready") for c in statuses)
        if ok:
            ready += 1
        if p["metadata"]["name"].startswith("traffic-generator") and \
                p.get("status", {}).get("phase") == "Running" and ok:
            tgen = True
    return ready, total, tgen


def chaos_objects():
    """List of (kind, name, stage_or_None, phase, params) currently in NS."""
    data = kubectl_json(["get", CHAOS_KINDS, "-n", NS])
    if data is None:
        return None
    out = []
    for it in data.get("items", []):
        kind = it.get("kind", "?")
        name = it["metadata"]["name"]
        m = re.search(r"stage-(\d)", name)
        stage = int(m.group(1)) if m else None
        phase = ""
        recs = it.get("status", {}).get("experiment", {}).get("containerRecords") or []
        if recs:
            phase = recs[0].get("phase", "")
        spec = it.get("spec", {})
        if kind == "NetworkChaos":
            params = "delay " + spec.get("delay", {}).get("latency", "?")
        elif kind == "StressChaos":
            params = json.dumps(spec.get("stressors", {}), sort_keys=True)
        elif kind == "PodChaos":
            params = spec.get("action", "?")
        else:
            params = ""
        out.append({"kind": kind, "name": name, "stage": stage,
                    "phase": phase, "params": params})
    return out


def service_ips():
    data = kubectl_json(["get", "svc", "-n", NS])
    ips = {}
    for s in (data or {}).get("items", []):
        ip = s.get("spec", {}).get("clusterIP")
        ports = s.get("spec", {}).get("ports") or []
        if ip and ip != "None" and ports:
            ips[s["metadata"]["name"]] = (ip, ports[0]["port"])
    return ips


def probe(url, timeout=8):
    """(seconds, http_code) — code may come from an HTTPError; None on no reply."""
    t0 = time.monotonic()
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            r.read(2048)
            return time.monotonic() - t0, r.status
    except urllib.error.HTTPError as e:
        return time.monotonic() - t0, e.code
    except Exception:  # noqa: BLE001
        return None, None


# ------------------------------------------------------------- scheduling --
class Bag:
    def __init__(self, items, rng):
        self.items, self.rng, self.q = list(items), rng, []

    def next(self):
        if not self.q:
            self.q = self.rng.sample(self.items, len(self.items))
        return self.q.pop(0)


def pick_gap_minutes(rng):
    if rng.random() < 0.10:
        return rng.uniform(30, 45)
    return rng.uniform(8, 22)


def parse_end_at(s):
    now = datetime.now()
    if s.startswith("+"):
        v = s[1:]
        if v.endswith("m"):
            return now + timedelta(minutes=float(v[:-1]))
        if v.endswith("h"):
            return now + timedelta(hours=float(v[:-1]))
        raise ValueError("relative --end-at needs m or h suffix")
    hh, mm = (int(x) for x in s.split(":"))
    t = now.replace(hour=hh, minute=mm, second=0, microsecond=0)
    if t <= now:
        t += timedelta(days=1)
    return t


# ------------------------------------------------------------- manifests --
def load_and_patch(manifest_dir, fname, stage_min, out_dir):
    """Patch stage/serial deadlines; return (patched_path, canonical_sha, wf_name)."""
    raw = open(os.path.join(manifest_dir, fname)).read()
    sha = hashlib.sha256(raw.encode()).hexdigest()[:16]
    total = 4 * stage_min + 1
    patched = raw.replace("deadline: 5m", f"deadline: {stage_min}m") \
                 .replace("deadline: 21m", f"deadline: {total}m")
    if patched.count(f"deadline: {stage_min}m") != 4:
        raise RuntimeError(f"{fname}: expected exactly 4 stage deadlines to patch")
    m = re.search(r"metadata:\n  name: (\S+)", patched)
    if not m:
        raise RuntimeError(f"{fname}: cannot find workflow name")
    path = os.path.join(out_dir, fname)
    with open(path, "w") as f:
        f.write(patched)
    return path, sha, m.group(1)


PODKILL_YAML = """apiVersion: chaos-mesh.org/v1alpha1
kind: PodChaos
metadata:
  name: {name}
  namespace: default
spec:
  action: pod-kill
  mode: one
  selector:
    namespaces:
      - default
    labelSelectors:
      app: {target}
"""


# --------------------------------------------------------------- episodes --
class Scheduler:
    def __init__(self, args):
        self.args = args
        self.rng = random.Random(args.seed)
        self.bag = Bag(parse_bag(args.bag), self.rng)
        self.stage_s = args.stage_minutes * 60
        self.end_at = parse_end_at(args.end_at)
        os.makedirs(args.log_dir, exist_ok=True)
        self.patched_dir = os.path.join(args.log_dir, "manifests_patched")
        os.makedirs(self.patched_dir, exist_ok=True)
        self.log = GroundTruthLog(os.path.join(args.log_dir, "chaos_ground_truth.jsonl"))
        self.census = {}
        self.episode_id = 0
        self.stop_heartbeat = threading.Event()
        self.ips = {}
        self.baselines = {}

    # -------------------------------------------------------- pre-run gate
    def pre_run_checks(self):
        ready, total, tgen = pods_ready()
        if ready < self.args.expected_pods:
            sys.exit(f"ABORT: only {ready}/{total} pods ready "
                     f"(need {self.args.expected_pods})")
        if not tgen:
            sys.exit("ABORT: traffic generator not running — negatives would be idle, "
                     "not normal")
        objs = chaos_objects()
        if objs is None or objs:
            sys.exit(f"ABORT: leftover chaos objects present: "
                     f"{[o['name'] for o in objs or []] or 'kubectl failed'}")
        rc, out = kubectl(["exec", "-n", "monitoring", "deploy/prometheus-server",
                           "-c", "prometheus-server", "--", "wget", "-qO-",
                           'http://localhost:9090/api/v1/query?query=count(up{job="kubernetes-pods"}==1)'],
                          timeout=30)
        n_targets = 0
        if rc == 0:
            try:
                n_targets = int(float(json.loads(out)["data"]["result"][0]["value"][1]))
            except Exception:  # noqa: BLE001
                pass
        if n_targets < 10:
            sys.exit(f"ABORT: Prometheus scraping {n_targets} pod targets, need >=10")
        free_gb = __import__("shutil").disk_usage("/").free / 2**30
        if free_gb < 5:
            sys.exit(f"ABORT: only {free_gb:.1f}GB disk free")

        self.ips = service_ips()
        probes = {v["probe"] for v in RAMPS.values()} | set(PODKILL_TARGETS.values())
        for svc, path in probes:
            if svc not in self.ips:
                sys.exit(f"ABORT: service {svc} not found")
            ip, port = self.ips[svc]
            times = []
            for _ in range(5):
                t, code = probe(f"http://{ip}:{port}{path}")
                if t is not None and code == 200:
                    times.append(t)
                time.sleep(1)
            if len(times) < 3:
                sys.exit(f"ABORT: baseline probe failing for {svc}{path}")
            times.sort()
            self.baselines[(svc, path)] = times[len(times) // 2]
        return n_targets, free_gb

    # ----------------------------------------------------------- heartbeat
    def heartbeat_loop(self):
        while not self.stop_heartbeat.wait(60):
            ready, total, _ = pods_ready()
            objs = chaos_objects()
            self.log.write({"type": "heartbeat", "pods_ready": ready,
                            "pods_total": total,
                            "chaos_objects": len(objs) if objs is not None else -1})

    # ------------------------------------------------------------ helpers
    def preflight(self):
        """Block until the cluster is clean or the end time passes."""
        while datetime.now() < self.end_at:
            ready, total, tgen = pods_ready()
            objs = chaos_objects()
            if ready >= self.args.expected_pods and tgen and objs == []:
                return True
            self.log.write({"type": "preflight-blocked", "pods_ready": ready,
                            "traffic_gen": tgen,
                            "chaos_objects": [o["name"] for o in objs or []]})
            time.sleep(120)
        return False

    def probe_ok(self, key):
        svc, path = key
        ip, port = self.ips[svc]
        t, code = probe(f"http://{ip}:{port}{path}")
        return t is not None and code == 200 and t < max(self.baselines[key] * 3, 1.0)

    def wait_recovery(self, key, timeout_s=300):
        t0 = time.time()
        while time.time() - t0 < timeout_s:
            ready, _, _ = pods_ready()
            if ready >= self.args.expected_pods and self.probe_ok(key):
                return round(time.time(), 3)
            time.sleep(10)
        return None

    def force_clean(self):
        kubectl(["delete", CHAOS_KINDS, "--all", "-n", NS, "--ignore-not-found",
                 "--wait=false"], timeout=60)
        for _ in range(12):
            if chaos_objects() == []:
                return True
            time.sleep(5)
        return False

    # ----------------------------------------------------- ramp episodes
    def run_ramp(self, scenario):
        cfg = RAMPS[scenario]
        path, sha, wf_name = load_and_patch(self.args.manifest_dir, cfg["file"],
                                            self.args.stage_minutes, self.patched_dir)
        ep = {"type": "episode", "episode_id": self.episode_id, "scenario": scenario,
              "target": cfg["target"], "manifest_sha": sha, "stages": [], "notes": ""}
        rc, _ = kubectl(["apply", "-f", path])
        ep["applied_ts"] = round(time.time(), 3)
        if rc != 0:
            ep["status"] = "failed-apply"
            return ep

        # verify injection: poll 10s up to 90s for any object reporting Injected
        injected = None
        t0 = time.time()
        while time.time() - t0 < 90:
            for o in chaos_objects() or []:
                if o["phase"] == "Injected":
                    injected = round(time.time(), 3)
                    break
            if injected:
                break
            time.sleep(10)
        if not injected:
            ep["status"] = "failed-verification"
            ep["notes"] = "no chaos object reached phase=Injected within 90s"
            kubectl(["delete", "workflow", wf_name, "-n", NS, "--ignore-not-found"])
            self.force_clean()
            return ep
        ep["injection_confirmed_ts"] = injected

        # observe stages until the workflow winds down (or hard margin)
        seen = {}
        total_s = 4 * self.stage_s + 60
        while time.time() - ep["applied_ts"] < total_s + 120:
            objs = chaos_objects()
            now = round(time.time(), 3)
            for o in objs or []:
                if o["kind"] in ("NetworkChaos", "StressChaos") and o["stage"]:
                    s = seen.setdefault(o["name"], {"stage": o["stage"],
                                                    "params": o["params"],
                                                    "start_ts": now, "phase": ""})
                    s["end_ts"] = now
                    if o["phase"]:
                        s["phase"] = o["phase"]
            if objs == [] and time.time() - ep["applied_ts"] > total_s * 0.9:
                break
            time.sleep(15)

        ep["stages"] = sorted(
            ({"stage": v["stage"], "params": v["params"], "phase": v["phase"],
              "start_ts": v["start_ts"], "end_ts": v["end_ts"]} for v in seen.values()),
            key=lambda x: x["stage"])
        stages_injected = sum(1 for s in ep["stages"] if s["phase"] == "Injected")
        if stages_injected < 4:
            ep["notes"] = f"only {stages_injected}/4 stages confirmed Injected"

        kubectl(["delete", "workflow", wf_name, "-n", NS, "--ignore-not-found"])
        if not self.force_clean():
            ep["status"] = "failed-cleanup"
            ep["notes"] += "; leftover chaos objects survived force clean"
            return ep
        ep["cleanup_confirmed_ts"] = round(time.time(), 3)

        rec = self.wait_recovery(cfg["probe"])
        if rec is None:
            ep["status"] = "failed-recovery"
            return ep
        ep["recovery_confirmed_ts"] = rec
        ep["status"] = "completed" if stages_injected == 4 else "partial"
        return ep

    # -------------------------------------------------- pod-kill episodes
    def run_podkill(self):
        target = self.rng.choice(sorted(PODKILL_TARGETS))
        probe_key = PODKILL_TARGETS[target]
        name = f"podkill-ep{self.episode_id}"
        path = os.path.join(self.patched_dir, f"{name}.yaml")
        with open(path, "w") as f:
            f.write(PODKILL_YAML.format(name=name, target=target))
        ep = {"type": "episode", "episode_id": self.episode_id, "scenario": "pod-kill",
              "target": target, "pod_kill": True, "stages": [], "notes": ""}

        pre = kubectl_json(["get", "pods", "-n", NS, "-l", f"app={target}"])
        old_uid = ""
        if pre and pre.get("items"):
            old_uid = pre["items"][0]["metadata"]["uid"]

        rc, _ = kubectl(["apply", "-f", path])
        ep["applied_ts"] = round(time.time(), 3)
        if rc != 0:
            ep["status"] = "failed-apply"
            return ep

        killed = None
        t0 = time.time()
        while time.time() - t0 < 120:
            cur = kubectl_json(["get", "pods", "-n", NS, "-l", f"app={target}"])
            uids = [i["metadata"]["uid"] for i in (cur or {}).get("items", [])]
            if uids and old_uid not in uids:
                killed = round(time.time(), 3)
                break
            time.sleep(10)
        kubectl(["delete", "podchaos", name, "-n", NS, "--ignore-not-found"])
        if not killed:
            ep["status"] = "failed-verification"
            ep["notes"] = "pod uid never changed — kill not observed"
            self.force_clean()
            return ep
        ep["injection_confirmed_ts"] = killed
        ep["stages"] = [{"stage": "kill", "params": "pod-kill",
                         "start_ts": killed, "end_ts": killed, "phase": "Injected"}]
        if not self.force_clean():
            ep["status"] = "failed-cleanup"
            return ep
        ep["cleanup_confirmed_ts"] = round(time.time(), 3)
        rec = self.wait_recovery(probe_key)
        if rec is None:
            ep["status"] = "failed-recovery"
            return ep
        ep["recovery_confirmed_ts"] = rec
        ep["status"] = "completed"
        return ep

    # ------------------------------------------------------------- main
    def episode_estimate_s(self, scenario):
        return (4 * self.stage_s + 360) if scenario != "pod-kill" else 360

    def run(self):
        n_targets, free_gb = self.pre_run_checks()
        header = {"type": "run_header", "run_id": self.args.run_id,
                  "seed": self.args.seed, "stage_minutes": self.args.stage_minutes,
                  "end_at": self.end_at.isoformat(timespec="seconds"),
                  "build_sha": self.args.build_sha,
                  "prometheus_targets": n_targets, "disk_free_gb": round(free_gb, 1),
                  "baselines_s": {f"{k[0]}{k[1]}": round(v, 4)
                                  for k, v in self.baselines.items()},
                  "manifest_sha": {}}
        for name, cfg in RAMPS.items():
            raw = open(os.path.join(self.args.manifest_dir, cfg["file"])).read()
            header["manifest_sha"][name] = hashlib.sha256(raw.encode()).hexdigest()[:16]
        self.log.write(header)

        hb = threading.Thread(target=self.heartbeat_loop, daemon=True)
        hb.start()
        end_reason = "completed"
        try:
            while True:
                scenario = self.bag.next()
                est = self.episode_estimate_s(scenario)
                if datetime.now() + timedelta(seconds=est) >= self.end_at:
                    break
                if not self.preflight():
                    end_reason = "end-at during preflight"
                    break
                self.episode_id += 1
                ep = self.run_ramp(scenario) if scenario != "pod-kill" \
                    else self.run_podkill()
                self.log.write(ep)
                self.census[ep["scenario"]] = self.census.get(ep["scenario"], {})
                self.census[ep["scenario"]][ep["status"]] = \
                    self.census[ep["scenario"]].get(ep["status"], 0) + 1

                gap_min = pick_gap_minutes(self.rng)
                gap_end = min(datetime.now() + timedelta(minutes=gap_min), self.end_at)
                q = {"type": "quiet", "start_ts": round(time.time(), 3),
                     "planned_minutes": round(gap_min, 1)}
                while datetime.now() < gap_end:
                    time.sleep(min(30, max(1, (gap_end - datetime.now()).total_seconds())))
                q["end_ts"] = round(time.time(), 3)
                self.log.write(q)
        except KeyboardInterrupt:
            end_reason = "interrupted"
        except Exception as e:  # noqa: BLE001
            end_reason = f"crashed: {type(e).__name__}: {e}"
        finally:
            self.stop_heartbeat.set()
            cleaned = self.force_clean()
            ready, total, _ = pods_ready()
            self.log.write({"type": "run_footer", "run_id": self.args.run_id,
                            "reason": end_reason, "episodes": self.episode_id,
                            "census": self.census, "final_clean": cleaned,
                            "final_pods_ready": f"{ready}/{total}"})
        return 0 if end_reason == "completed" else 1


# ----------------------------------------------------------------- dry run --
def dry_run(args):
    rng = random.Random(args.seed)
    bag = Bag(parse_bag(args.bag), rng)
    end_at = parse_end_at(args.end_at)
    clock = datetime.now()
    stage_s = args.stage_minutes * 60
    counts, gaps, n = {}, [], 0
    os.makedirs(args.log_dir, exist_ok=True)
    patched_dir = os.path.join(args.log_dir, "manifests_patched")
    os.makedirs(patched_dir, exist_ok=True)
    for name, cfg in RAMPS.items():
        _, sha, wf = load_and_patch(args.manifest_dir, cfg["file"],
                                    args.stage_minutes, patched_dir)
        print(f"  manifest ok: {name} (workflow={wf}, sha={sha})")
    print(f"\nsimulated night — seed={args.seed}, stages={args.stage_minutes}m, "
          f"end={end_at:%H:%M}")
    while True:
        scenario = bag.next()
        est = (4 * stage_s + 360) if scenario != "pod-kill" else 360
        if clock + timedelta(seconds=est) >= end_at:
            break
        n += 1
        target = rng.choice(sorted(PODKILL_TARGETS)) if scenario == "pod-kill" else ""
        print(f"  ep{n:>3} {clock:%H:%M} {scenario:<22} {target}")
        counts[scenario] = counts.get(scenario, 0) + 1
        clock += timedelta(seconds=est)
        gap = pick_gap_minutes(rng)
        gaps.append(gap)
        clock += timedelta(minutes=gap)
    print(f"\nepisodes: {n}")
    for k in sorted(counts):
        print(f"  {k:<22} {counts[k]}")
    if gaps:
        print(f"gaps: min={min(gaps):.1f}m max={max(gaps):.1f}m "
              f"mean={sum(gaps)/len(gaps):.1f}m")
    ok = n >= 3 and (not gaps or min(gaps) >= 8)
    print("GATE:", "PASS" if ok else "CHECK — thin schedule or gap floor violated")
    return 0


