#!/usr/bin/env python3
"""Randomised chaos scheduler for the v2 collection run.

Injects the four verified ramped workflows plus pod-kill in shuffled-bag order
with randomised quiet gaps, and writes a ground-truth JSONL log trustworthy
enough to become training labels. Design: Chaos_Scheduler_Plan.md.

Hard invariant: a window is only logged as "fault" if injection was OBSERVED
(chaos object reports phase == Injected), and only logged as "quiet" if cleanup
and recovery were CONFIRMED. Anything unverifiable is marked and discarded by
the extraction pipeline, never guessed.

Stdlib only. Runs ON the VM (kubectl local) under tmux.
"""

